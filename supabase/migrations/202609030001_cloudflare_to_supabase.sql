-- 0053_push_subscriptions.sql
-- 창을 닫아도 알림이 도착하려면, 어디로 보낼지를 서버가 들고 있어야 한다.
--
-- 브라우저가 알림을 허용하면 "이 기기로 밀어 주세요"라는 주소(endpoint)와
