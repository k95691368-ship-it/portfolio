-- 쌓이는 기록이라야 증거가 된다.
--
-- 행위자는 사용자 id 가 아니라 그 시점의 이름으로 남긴다. 계정이 나중에
-- 삭제돼도 누가 했는지는 남아야 하고, 외래키로 묶어 두면 계정 삭제가 이
-- 표 때문에 실패한다.
