--
-- 소급해서 채우지 않는다. 이 컬럼이 생기기 전 세션이 어떻게 만들어졌는지는
-- 아무도 모르고, 모르는 것을 아는 것처럼 적으면 그 기록 전체를 믿을 수 없게
