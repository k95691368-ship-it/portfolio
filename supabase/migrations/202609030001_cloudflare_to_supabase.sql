-- 대소문자만 바꿔 가입하면 남이 낸 지원 내역과 접수번호가 "내 지원 현황"에
-- 그대로 보였다.
--
-- 애플리케이션이 저장·조회 전에 소문자로 통일하도록 고쳤고, 여기서 DB 차원의
-- 제약을 더해 우회 경로를 남기지 않는다.

-- 기존 행을 같은 규칙으로 정리한다 (이미 소문자면 바뀌는 것이 없다).
UPDATE users SET email = LOWER(TRIM(email)) WHERE email <> LOWER(TRIM(email));

-- 이제부터는 표기가 달라도 같은 이메일로 두 계정을 만들 수 없다.
CREATE UNIQUE INDEX idx_users_email_lower ON users(LOWER(email));

-- 0032_signature_revocations.sql
-- 서명 후 계약 내용이 바뀌면 기존 서명을 무효화한다.
--
-- 지금까지 계약 내용을 잠그는 조건은 interview_rooms.status = 'signed' 하나였고,
-- 그 상태는 양측이 모두 서명한 뒤에야 붙었다. 그래서 지원자가 먼저 서명한
-- 상태에서 회사가 기본급과 계약서 본문을 바꾸고 이어서 서명하면, 지원자가 본
-- 적도 없는 조건에 지원자 서명이 붙은 계약이 만들어졌다.
--
-- 증거가 약한 문제가 아니라 서로 합의한 내용이 없는 문제다. 내용이 바뀌면
-- 그 전에 받은 서명은 더 이상 그 내용에 대한 동의가 아니므로 무효로 옮기고,
-- 상대방에게 다시 서명을 받아야 한다. 무효화된 서명도 지우지 않고 남겨,
-- 무엇이 언제 왜 무효가 되었는지 계약 이력으로 증명할 수 있게 한다.
CREATE TABLE signature_revocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id TEXT NOT NULL REFERENCES interview_rooms(id),
  signer_role TEXT NOT NULL,
  signer_user_id TEXT REFERENCES users(id),
  signed_at TEXT,
  signer_ip TEXT,
  signer_user_agent TEXT,
  signer_country TEXT,
  revoked_at TEXT NOT NULL DEFAULT (datetime('now')),
  revoked_by_user_id TEXT REFERENCES users(id),
  reason TEXT NOT NULL
);

CREATE INDEX idx_signature_revocations_room ON signature_revocations(room_id, id);

-- 0033_signature_document_hash.sql
-- 서명을 서명 대상 문서에 묶는다.
--
-- 전자서명이 "이 문서에 서명했다"를 뜻하려면 서명과 문서가 연결돼 있어야 한다.
-- 그런데 signatures 에는 서명 그림과 접속 흔적(IP·기기·국가)만 있고 어떤 내용에
-- 붙었는지가 없었다. 다툼이 생겨 "나는 그 조건에 동의하지 않았다"는 주장이
-- 나오면, 서명 데이터만으로는 무엇에 동의한 것인지 특정할 수 없었다.
--
-- 존재하는 유일한 지문은 서명이 다 끝난 뒤 회사가 올린 PDF 바이트에 대한
-- signed_contracts.sha256_hash 인데, 서명 행과 연결되지 않고 시점도 늦고
-- 회사가 버튼을 눌러야 생긴다.
--
-- 서명하는 순간 계약 내용의 지문을 계산해 서명과 함께 남긴다.
ALTER TABLE signatures ADD COLUMN document_sha256 TEXT;

-- 무효화된 서명에도 무엇에 붙어 있었는지를 남긴다.
ALTER TABLE signature_revocations ADD COLUMN document_sha256 TEXT;

-- 0034_contract_deliveries.sql
-- 근로계약서 교부 이력.
--
-- 근로기준법 제17조 제2항은 사용자가 근로계약서를 근로자에게 교부하도록 하고,
-- 위반은 제114조 벌금 대상이다. 그런데 이 앱에서 교부는 회사가 계약서 화면에서
-- 버튼을 한 번 누르는 데 달려 있었다. 누르지 않으면 계약은 'signed'로 끝나지만
-- 교부물이 아예 없고, 근로자에게 가는 것은 "계약서를 확인해보세요"라는 인앱
-- 알림 하나뿐이었다.
--
-- 받은 기록도 없었다. signed_contracts 에는 수신자 컬럼이 없고(최종합격 이메일
-- 표에는 recipient_email 이 있는데 계약서 쪽에만 없다) 다운로드 로그도 남지
-- 않아, 전자문서법 제5조가 요구하는 수신자·수신일시 보존이 함께 깨졌다.
--
-- 교부를 별도 표로 분리한 이유: PDF를 다시 저장하면 signed_contracts 의
-- emailed_at 이 NULL 로 리셋되어 교부 이력이 지워졌다. 교부는 한 번 일어난
-- 사실이므로 문서 저장과 생애주기를 분리한다.
CREATE TABLE contract_deliveries (
  id TEXT PRIMARY KEY,
  room_id TEXT NOT NULL REFERENCES interview_rooms(id),
  recipient_user_id TEXT REFERENCES users(id),
  -- in_app: 체결 즉시 서버가 만드는 열람 가능 상태
  -- email: 이메일 발송
  -- download: 근로자가 직접 내려받음
  -- paper: 전자 수신을 원하지 않는 근로자에게 인쇄해 교부
  channel TEXT NOT NULL CHECK (channel IN ('in_app', 'email', 'download', 'paper')),
  recipient_address TEXT,
  status TEXT NOT NULL DEFAULT 'delivered',
  error_message TEXT,
  attempt_count INTEGER NOT NULL DEFAULT 1,
  delivered_at TEXT NOT NULL DEFAULT (datetime('now')),
  first_viewed_at TEXT,
  downloaded_at TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX idx_contract_deliveries_room ON contract_deliveries(room_id, id);
-- 채널마다 한 행만 두어, 같은 채널의 교부가 중복으로 쌓이지 않게 한다.
CREATE UNIQUE INDEX idx_contract_deliveries_room_channel
  ON contract_deliveries(room_id, channel);

