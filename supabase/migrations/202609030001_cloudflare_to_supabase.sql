ALTER TABLE sessions ADD COLUMN scoped_room_id TEXT;

-- 참고: 0050 의 room_access_sessions 는 더 이상 쓰지 않는다.
-- 코드 입장이 별도 출입증이 아니라 계정 로그인으로 바뀌었기 때문이다.
-- 다만 표와 그 안의 행은 지우지 않는다 -- 그 기간에 누가 언제 어느 기기로
-- 방을 열었는지의 유일한 기록이고, 이 저장소는 증거를 지우지 않는다.

