-- 휴게시간.
--
-- 계약서 인쇄본의 소정근로시간 줄은 이렇게 찍히고 있었다.
--
--   09:00부터 18:00까지 (휴게시간 : __시 __분 ~ __시 __분)
--
-- 괄호 안이 상수로 박힌 빈칸이었다. 입력란도 없고 저장하는 칸도 없으니
-- 채울 방법 자체가 없었다. 서명하고 보관하고 지원자에게 교부되는 문서에
-- 빈칸 하나가 언제나 남는다.
--
-- 휴게시간은 적어도 되는 항목이 아니다.
--
--   근로기준법 제54조는 4시간 근로에 30분 이상, 8시간 근로에 1시간 이상의
--   휴게를 근로시간 도중에 주도록 한다.
--
--   같은 법 제17조 제1항 제5호와 시행령 제8조 제2호는 제93조 제1호의 사항을
--   근로계약에 명시하도록 하는데, 제93조 제1호가 '업무의 시작과 종료 시각,
--   휴게시간'이다. 즉 계약서에 적어야 하는 값이다.
--
-- 정본 직렬화(TERM_ORDER)에는 넣지 않는다. 줄을 하나 더하면 이미 서명된
-- 계약서의 지문이 소급해 바뀌어, 아무도 손대지 않은 계약이 '내용이 바뀜'으로
-- 뒤집힌다. 서명 직전 변경은 화면이 읽은 저장 시각(termsUpdatedAt)으로 막는다.
ALTER TABLE contract_terms ADD COLUMN break_time TEXT;
