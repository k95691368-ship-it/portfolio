-- 새 메시지를 상대에게 알리기 위해 필요한 두 가지.
--
-- 하나. 이 방에서 마지막으로 '새 메시지' 메일을 언제 보냈는가.
--
-- 대화는 한 번에 여러 줄이 오간다. 줄마다 메일을 보내면 지원자의 메일함이
-- 막히고, 그러면 정작 중요한 메일(서류합격, 최종합격)이 그 사이에 묻힌다.
-- 첫 줄에만 보내고 그 뒤 한동안은 조용히 있기 위해 시각을 남긴다.
--
-- 방에 두는 이유는, 조용히 할 대상이 '이 대화'이기 때문이다. 사람에 두면
-- 다른 방의 대화까지 함께 막힌다.
ALTER TABLE interview_rooms ADD COLUMN last_message_email_at TEXT;

-- 둘. 이 사람이 마지막으로 화면을 열어 둔 시각.
--
-- 눈앞에서 대화하는 사람에게 "새 메시지가 도착했습니다" 메일을 보내는 것은
-- 알림이 아니라 방해다. 방금까지 보고 있었으면 보내지 않는다.
--
-- 로그인 시각이 아니라 열람 시각이다. 로그인은 30일 유지되므로 그것으로는
-- 지금 보고 있는지 알 수 없다.
ALTER TABLE users ADD COLUMN last_seen_at TEXT;
