-- 이 세션이 어떻게 만들어졌는가, 그리고 어느 방까지인가.
--
-- 면접방 입장 코드가 로그인 수단이 되면서 필요해졌다.
--
-- 코드는 회사 담당자도 볼 수 있다(발급 화면·지원서 상세·재발송). 그러면
-- 담당자가 그 코드로 지원자 계정에 로그인해 근로자 서명을 대신 만들 수 있다.
-- 그런데 지금 서명 기록은 그것을 '계정 비밀번호로 확인된 세션'이라고 적는다 --
-- 없는 근거를 있는 것처럼 부르는 것이고, 이 앱이 만들려는 증명서 자체가
-- 거짓이 된다. 0036 이 금지한 바로 그것이다.
--
-- 막지는 않는다(코드로 서명까지 되는 것이 정해진 방향이다). 대신 어떻게
-- 인증했는지를 그대로 남긴다. 감사추적증명서가 그 값을 문장으로 옮기므로,
-- 나중에 다투는 자리에서 '비밀번호로 확인한 서명'과 '코드로 들어와 한 서명'이
-- 구분된다.
--
-- 소급해서 채우지 않는다. 이 컬럼이 생기기 전 세션이 어떻게 만들어졌는지는
-- 아무도 모르고, 모르는 것을 아는 것처럼 적으면 그 기록 전체를 믿을 수 없게
-- 된다. NULL 은 '기록 없음'이고 비밀번호 로그인으로 읽는다.
ALTER TABLE sessions ADD COLUMN auth_method TEXT;

-- 코드로 만든 세션은 그 방에서만 쓴다.
--
-- 코드는 회사가 한 지원자에게 건넨 값이지 계정 비밀번호가 아니다. 그것으로
-- 대시보드와 다른 방까지 열리면, 코드 한 줄이 계정 전체의 열쇠가 된다.
-- 발급된 방 id 를 세션에 박아 두고 그 방 밖에서는 이 세션을 쓰지 않는다.
--
-- 비밀번호 로그인 세션은 NULL 이다 -- 방에 매이지 않는다는 뜻이다.
ALTER TABLE sessions ADD COLUMN scoped_room_id TEXT;

-- 참고: 0050 의 room_access_sessions 는 더 이상 쓰지 않는다.
-- 코드 입장이 별도 출입증이 아니라 계정 로그인으로 바뀌었기 때문이다.
-- 다만 표와 그 안의 행은 지우지 않는다 -- 그 기간에 누가 언제 어느 기기로
-- 방을 열었는지의 유일한 기록이고, 이 저장소는 증거를 지우지 않는다.
