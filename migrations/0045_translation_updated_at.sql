-- 같은 언어를 다시 번역하면 최초 번역 시각이 사라졌다.
--
-- contract_translations 는 (room_id, language) 당 한 행이고, 재번역은
-- created_at 을 현재 시각으로 덮어썼다. 감사추적의 '외국어 계약서 생성'
-- 이벤트는 이 값 하나만 보므로, 서명 전에 만들어 근로자가 읽은 번역본이
-- 이력에서는 서명 뒤에 처음 생긴 것으로 바뀐다.
--
-- 외국인 근로자가 서명 시점에 자기 언어로 계약서를 읽을 수 있었는가는
-- 다툼이 생겼을 때 핵심이 되는 사실이다. 그 사실이 정반대로 기록된다.
--
-- 처음 만든 시각은 그대로 두고, 다시 만든 시각을 따로 남긴다.
ALTER TABLE contract_translations ADD COLUMN updated_at TEXT;
